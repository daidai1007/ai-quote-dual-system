-- Verified online 2026-09-11: the original four-column UNIQUE blocks source reuse
-- across versions. Preserve its legacy (NULL-version) uniqueness and extend it.
-- Create the replacement before dropping the original; never use CASCADE.
DO $$
DECLARE old_definition text; new_definition text;
BEGIN
  IF current_setting('server_version_num')::integer<150000 THEN
    RAISE EXCEPTION 'Source-version uniqueness requires PostgreSQL 15 or later';
  END IF;
  SELECT pg_get_constraintdef(oid) INTO old_definition FROM pg_constraint
    WHERE conrelid='calc.attachment_price'::regclass AND conname='uq_attachment_price_source';
  IF old_definition IS NOT NULL AND old_definition<>'UNIQUE (source_file, source_sheet, source_row_no, price_source)' THEN
    RAISE EXCEPTION 'Unexpected source constraint; stop and inspect: %',old_definition;
  END IF;
  SELECT pg_get_constraintdef(oid) INTO new_definition FROM pg_constraint
    WHERE conrelid='calc.attachment_price'::regclass AND conname='uq_attachment_price_source_version';
  IF new_definition IS NULL THEN
    ALTER TABLE calc.attachment_price ADD CONSTRAINT uq_attachment_price_source_version
      UNIQUE NULLS NOT DISTINCT(source_file,source_sheet,source_row_no,price_source,data_version);
  ELSIF new_definition<>'UNIQUE NULLS NOT DISTINCT (source_file, source_sheet, source_row_no, price_source, data_version)' THEN
    RAISE EXCEPTION 'Unexpected versioned source constraint; stop and inspect: %',new_definition;
  END IF;
  IF old_definition IS NOT NULL THEN
    ALTER TABLE calc.attachment_price DROP CONSTRAINT uq_attachment_price_source;
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS calc.attachment_cost_rule (
  rule_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data_version text NOT NULL REFERENCES calc.attachment_catalog_version(data_version),import_key text NOT NULL,
  category_level1 text NOT NULL,category_level2 text NOT NULL DEFAULT '',item_name text NOT NULL,
  model_code text,color text,unit text,method text NOT NULL CHECK(method IN ('FIXED','CALCULATED')),
  fixed_cost numeric,formulas jsonb NOT NULL DEFAULT '{}',auxiliary_list text NOT NULL DEFAULT '',
  weight_not_applicable boolean NOT NULL DEFAULT false,issues jsonb NOT NULL DEFAULT '[]',
  source_file text NOT NULL,source_sheet text NOT NULL,source_row_no integer NOT NULL,
  raw_values jsonb NOT NULL,notes text,UNIQUE(data_version,import_key),UNIQUE(rule_id,data_version),
  CHECK((method='FIXED' AND fixed_cost>=0 AND fixed_cost IS NOT NULL) OR (method='CALCULATED' AND fixed_cost IS NULL))
);
CREATE TABLE IF NOT EXISTS calc.attachment_cost_rule_product (
  rule_id bigint NOT NULL REFERENCES calc.attachment_cost_rule(rule_id),product_code text NOT NULL,
  PRIMARY KEY(rule_id,product_code)
);
CREATE TABLE IF NOT EXISTS calc.attachment_cost_rule_material (
  rule_id bigint NOT NULL REFERENCES calc.attachment_cost_rule(rule_id),
  material_code text NOT NULL CHECK(material_code IN ('SECC','SUS304','SUS316')),
  PRIMARY KEY(rule_id,material_code)
);
ALTER TABLE calc.attachment_cost_rule ADD COLUMN IF NOT EXISTS model_semantics text NOT NULL DEFAULT 'MODEL'
  CHECK(model_semantics IN ('MODEL','MATERIAL','DESCRIPTION'));
CREATE TABLE IF NOT EXISTS calc.attachment_cost_rule_binding (
  attachment_price_id bigint NOT NULL REFERENCES calc.attachment_price(attachment_price_id),
  rule_id bigint NOT NULL REFERENCES calc.attachment_cost_rule(rule_id),
  PRIMARY KEY(attachment_price_id,rule_id)
);
CREATE TABLE IF NOT EXISTS calc.attachment_cost_rule_parameter (
  rule_id bigint NOT NULL REFERENCES calc.attachment_cost_rule(rule_id),name text NOT NULL,
  source text NOT NULL CHECK(source IN ('ENVIRONMENT','MANUAL')),unit text NOT NULL,
  required boolean NOT NULL,PRIMARY KEY(rule_id,name),
  CHECK((source='ENVIRONMENT' AND name IN ('宽度','高度','深度','材质密度','材质单价','喷塑单价'))
     OR (source='MANUAL' AND name NOT IN ('宽度','高度','深度','材质密度','材质单价','喷塑单价')))
);

-- Quote line identity is independent of product/model text and exists before document confirmation.
CREATE TABLE IF NOT EXISTS calc.attachment_quote_line (
  quote_line_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),quote_id varchar(80) NOT NULL,
  product_code varchar(40) NOT NULL,environment_snapshot jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),UNIQUE(quote_line_id,quote_id),
  CHECK(jsonb_typeof(environment_snapshot)='object'
    AND environment_snapshot ?& ARRAY['product_code','width_mm','height_mm','depth_mm','material_code','density_g_cm3','material_unit_price','spray_unit_price','coating_type','quote_date']
    AND environment_snapshot->>'product_code'=product_code
    AND jsonb_typeof(environment_snapshot->'width_mm')='number' AND (environment_snapshot->>'width_mm')::numeric>0
    AND jsonb_typeof(environment_snapshot->'height_mm')='number' AND (environment_snapshot->>'height_mm')::numeric>0
    AND jsonb_typeof(environment_snapshot->'depth_mm')='number' AND (environment_snapshot->>'depth_mm')::numeric>0)
);
