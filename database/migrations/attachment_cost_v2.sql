CREATE OR REPLACE VIEW calc.v_attachment_selection_dual_cost AS
SELECT s.attachment_selection_id,s.quote_id,s.quote_line_id,s.attachment_price_id,s.quantity,s.price_sign,
       s.calculation_status,s.quick_face_price,s.quick_amount,s.formula_unit_cost,s.formula_amount,
       s.cost_rule_id,s.rule_version,s.catalog_version,s.manual_inputs,s.environment_snapshot,s.cost_snapshot,s.error_message
FROM calc.attachment_selection s WHERE s.calculation_status IS NOT NULL;
COMMENT ON VIEW calc.v_attachment_selection_dual_cost IS '仅快照，无当前目录回查；历史legacy记录不会被虚构为FIXED或QUICK_ONLY。';

CREATE OR REPLACE VIEW calc.v_attachment_catalog_v2 AS
SELECT ap.attachment_price_id,c.category_level1,coalesce(c.category_level2,'') AS category_level2,coalesce(c.category_level3,'') AS category_level3,
       ap.item_name,ap.model_code,ap.unit,ap.color,ap.width_mm,ap.height_mm,ap.depth_mm,
       ap.quick_face_price AS price,ap.data_version,ap.source_file,ap.source_sheet,ap.source_row_no,ap.source_sha256
FROM calc.attachment_price ap JOIN calc.attachment_classification c USING(attachment_price_id)
JOIN calc.attachment_catalog_version v ON v.data_version=ap.data_version
WHERE ap.is_active AND v.status='ACTIVE';
COMMENT ON VIEW calc.v_attachment_catalog_v2 IS 'V2目录接口必须读此视图：price为完整精度面价，按ID保留不同分类，不做名称去重。';

CREATE OR REPLACE FUNCTION calc.get_attachment_dual_fee(p_quote_line_id uuid)
RETURNS TABLE(quick_fee numeric,formula_fee numeric,error_count bigint,quick_only_count bigint)
LANGUAGE sql STABLE AS $$
  SELECT coalesce(sum(quick_amount),0),
         CASE WHEN count(*) FILTER(WHERE calculation_status='ERROR')>0 THEN NULL ELSE coalesce(sum(formula_amount) FILTER(WHERE calculation_status IN ('FIXED','CALCULATED')),0) END,
         count(*) FILTER(WHERE calculation_status='ERROR'),count(*) FILTER(WHERE calculation_status='QUICK_ONLY')
  FROM calc.v_attachment_selection_dual_cost WHERE quote_line_id=p_quote_line_id;
$$;
CREATE OR REPLACE FUNCTION calc.get_attachment_formula_fee_strict(p_quote_line_id uuid)
RETURNS numeric LANGUAGE plpgsql STABLE AS $$ DECLARE fees record; BEGIN
  IF NOT EXISTS(SELECT 1 FROM calc.attachment_quote_line WHERE quote_line_id=p_quote_line_id) THEN RAISE EXCEPTION '报价行不存在'; END IF;
  SELECT * INTO fees FROM calc.get_attachment_dual_fee(p_quote_line_id);
  IF fees.error_count>0 THEN RAISE EXCEPTION '附件成本计算失败，不能生成完整公式报价（%项）',fees.error_count; END IF;
  RETURN fees.formula_fee;
END $$;

-- Select specificity before checking rule issues: broken specific rules never fall back to generic.
CREATE OR REPLACE FUNCTION calc.resolve_attachment_cost_rule(p_attachment_price_id bigint,p_product_code text,p_material_code text)
RETURNS bigint LANGUAGE plpgsql STABLE AS $$ DECLARE candidates bigint[]; product_candidates bigint[]; BEGIN
  SELECT array_agg(r.rule_id) INTO product_candidates
  FROM calc.attachment_cost_rule_binding b JOIN calc.attachment_cost_rule r USING(rule_id)
  WHERE b.attachment_price_id=p_attachment_price_id AND
    (NOT EXISTS(SELECT 1 FROM calc.attachment_cost_rule_product p WHERE p.rule_id=r.rule_id)
     OR EXISTS(SELECT 1 FROM calc.attachment_cost_rule_product p WHERE p.rule_id=r.rule_id AND p.product_code=p_product_code));
  IF coalesce(cardinality(product_candidates),0)=0 THEN RETURN NULL; END IF;
  IF EXISTS(SELECT 1 FROM calc.attachment_cost_rule_material m WHERE m.rule_id=ANY(product_candidates))
    AND (p_material_code IS NULL OR p_material_code NOT IN ('SECC','SUS304','SUS316')) THEN
    RAISE EXCEPTION '材质适用规则需要有效材质：SECC、SUS304或SUS316';
  END IF;
  WITH candidates AS (
    SELECT r.rule_id,CASE WHEN EXISTS(SELECT 1 FROM calc.attachment_cost_rule_product p WHERE p.rule_id=r.rule_id AND p.product_code=p_product_code) THEN 1 ELSE 0 END AS priority
    FROM calc.attachment_cost_rule_binding b JOIN calc.attachment_cost_rule r USING(rule_id)
    WHERE b.attachment_price_id=p_attachment_price_id AND r.rule_id=ANY(product_candidates) AND
      (NOT EXISTS(SELECT 1 FROM calc.attachment_cost_rule_material m WHERE m.rule_id=r.rule_id)
       OR EXISTS(SELECT 1 FROM calc.attachment_cost_rule_material m WHERE m.rule_id=r.rule_id AND m.material_code=p_material_code))
  ) SELECT array_agg(rule_id) INTO candidates FROM candidates WHERE priority=(SELECT max(priority) FROM candidates);
  IF coalesce(cardinality(candidates),0)=0 THEN RAISE EXCEPTION '当前材质 % 缺少附件成本规则',p_material_code; END IF;
  IF cardinality(candidates)>1 THEN RAISE EXCEPTION '同级成本规则冲突：%',candidates; END IF;
  RETURN candidates[1];
END $$;
-- Old V2 callers may resolve unrestricted rules; material-dependent rules require the third argument.
CREATE OR REPLACE FUNCTION calc.resolve_attachment_cost_rule(p_attachment_price_id bigint,p_product_code text)
RETURNS bigint LANGUAGE sql STABLE AS $$
  SELECT calc.resolve_attachment_cost_rule(p_attachment_price_id,p_product_code,NULL::text);
$$;
REVOKE ALL ON FUNCTION calc.resolve_attachment_cost_rule(bigint,text) FROM PUBLIC;
