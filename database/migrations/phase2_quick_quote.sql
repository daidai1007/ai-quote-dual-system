/*
  V1.1: independent quick-quote experience library and dual quote API.

  Quick quotation is deliberately independent from the formula quotation:
  - it only reads calc.quick_quote_experience;
  - it never calls a part rule, material-weight formula or area formula;
  - matched base price = experience price × input perimeter / matched perimeter;
  - final quick cost = adjusted experience base price + selected attachment fee;
  - no match returns NULL plus quick_quote_missing, never 0.

  Run after the V1.0 database scripts (and after the formula total function).
*/
BEGIN;

CREATE TABLE IF NOT EXISTS calc.quick_quote_experience (
  quick_rule_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_code VARCHAR(40) NOT NULL,
  model_code VARCHAR(100),
  material_code VARCHAR(30) NOT NULL,
  reference_width_mm NUMERIC(12,3) NOT NULL CHECK (reference_width_mm > 0),
  reference_height_mm NUMERIC(12,3) NOT NULL CHECK (reference_height_mm > 0),
  reference_depth_mm NUMERIC(12,3) NOT NULL CHECK (reference_depth_mm > 0),
  min_width_mm NUMERIC(12,3),
  max_width_mm NUMERIC(12,3),
  min_height_mm NUMERIC(12,3),
  max_height_mm NUMERIC(12,3),
  min_depth_mm NUMERIC(12,3),
  max_depth_mm NUMERIC(12,3),
  quick_material_cost NUMERIC(14,6),
  quick_auxiliary_cost NUMERIC(14,6),
  quick_labor_cost NUMERIC(14,6),
  quick_attachment_fee NUMERIC(14,6),
  quick_spray_cost NUMERIC(14,6),
  quick_management_fee NUMERIC(14,6),
  quick_base_price NUMERIC(14,6),
  quick_total_cost NUMERIC(14,6) NOT NULL CHECK (quick_total_cost >= 0),
  effective_from DATE NOT NULL DEFAULT CURRENT_DATE,
  effective_to DATE,
  source_file VARCHAR(255),
  source_sheet VARCHAR(128),
  source_row_no INTEGER,
  notes TEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT ck_quick_quote_material
    CHECK (material_code IN ('SECC','SUS304','SUS316')),
  CONSTRAINT ck_quick_quote_period
    CHECK (effective_to IS NULL OR effective_to > effective_from),
  CONSTRAINT ck_quick_quote_ranges
    CHECK ((min_width_mm IS NULL OR max_width_mm IS NULL OR max_width_mm >= min_width_mm)
       AND (min_height_mm IS NULL OR max_height_mm IS NULL OR max_height_mm >= min_height_mm)
       AND (min_depth_mm IS NULL OR max_depth_mm IS NULL OR max_depth_mm >= min_depth_mm))
);

ALTER TABLE calc.quick_quote_experience
  ADD COLUMN IF NOT EXISTS quick_base_price NUMERIC(14,6);

CREATE INDEX IF NOT EXISTS idx_quick_quote_lookup
  ON calc.quick_quote_experience
     (product_code, material_code, is_active, effective_from DESC);
CREATE INDEX IF NOT EXISTS idx_quick_quote_model
  ON calc.quick_quote_experience(product_code, model_code, material_code);

CREATE UNIQUE INDEX IF NOT EXISTS uq_quick_quote_active_key
  ON calc.quick_quote_experience(
    product_code, COALESCE(model_code,''), material_code,
    reference_width_mm, reference_height_mm, reference_depth_mm,
    effective_from
  );

COMMENT ON TABLE calc.quick_quote_experience IS
  'Independent quick quotation base prices. The matcher reads quick_base_price only; formula tables and component formulas are not consulted.';
COMMENT ON COLUMN calc.quick_quote_experience.quick_total_cost IS
  'Legacy alias for the direct experience base price; the dual API adds selected attachment fee.';
COMMENT ON COLUMN calc.quick_quote_experience.quick_base_price IS
  'Direct experience base price from the quick-quote workbook; not derived from material weight, area, labor or parts.';

CREATE OR REPLACE FUNCTION calc.match_quick_quote(
  p_product_code VARCHAR,
  p_model_code VARCHAR DEFAULT NULL,
  p_material_code VARCHAR DEFAULT 'SECC',
  p_width_mm NUMERIC DEFAULT NULL,
  p_height_mm NUMERIC DEFAULT NULL,
  p_depth_mm NUMERIC DEFAULT NULL,
  p_as_of_date DATE DEFAULT CURRENT_DATE
)
RETURNS TABLE (
  quick_rule_id BIGINT,
  product_code VARCHAR,
  model_code VARCHAR,
  material_code VARCHAR,
  reference_width_mm NUMERIC,
  reference_height_mm NUMERIC,
  reference_depth_mm NUMERIC,
  quick_material_cost NUMERIC,
  quick_auxiliary_cost NUMERIC,
  quick_labor_cost NUMERIC,
  quick_attachment_fee NUMERIC,
  quick_spray_cost NUMERIC,
  quick_management_fee NUMERIC,
  quick_total_cost NUMERIC,
  match_method VARCHAR,
  dimension_distance NUMERIC
)
LANGUAGE SQL
STABLE
AS $function$
  WITH canonical AS (
    SELECT CASE p_product_code
      WHEN 'JC' THEN 'JC_EXP'
      WHEN 'JQ' THEN 'JQ_EXP'
      WHEN U&'\8D85\5BBDJP' THEN 'JP_WIDE_EXP'
      WHEN U&'\8D85\5BBDJS' THEN 'JS_WIDE_EXP'
      WHEN U&'\64CD\4F5C\53F0' THEN 'OP_TABLE_EXP'
      ELSE p_product_code END AS product_code
  ), candidates AS (
    SELECT q.*,
      CASE WHEN NULLIF(p_model_code,'') IS NOT NULL
                 AND NULLIF(q.model_code,'') = NULLIF(p_model_code,'')
           THEN 0 ELSE 1 END AS model_rank,
      CASE WHEN p_width_mm BETWEEN COALESCE(q.min_width_mm,q.reference_width_mm)
                              AND COALESCE(q.max_width_mm,q.reference_width_mm)
                 AND p_height_mm BETWEEN COALESCE(q.min_height_mm,q.reference_height_mm)
                              AND COALESCE(q.max_height_mm,q.reference_height_mm)
                 AND p_depth_mm BETWEEN COALESCE(q.min_depth_mm,q.reference_depth_mm)
                              AND COALESCE(q.max_depth_mm,q.reference_depth_mm)
           THEN 0 ELSE 1 END AS range_rank,
      sqrt(power(p_width_mm-q.reference_width_mm,2)
         + power(p_height_mm-q.reference_height_mm,2)
         + power(p_depth_mm-q.reference_depth_mm,2)) AS distance
    FROM calc.quick_quote_experience q
    CROSS JOIN canonical c
    WHERE q.product_code = c.product_code
      AND q.material_code = p_material_code
      AND q.is_active = TRUE
      AND q.effective_from <= p_as_of_date
      AND (q.effective_to IS NULL OR p_as_of_date < q.effective_to)
      AND p_width_mm IS NOT NULL AND p_height_mm IS NOT NULL AND p_depth_mm IS NOT NULL
  ), best AS (
    SELECT *
    FROM candidates
    ORDER BY model_rank, range_rank, distance, effective_from DESC, quick_rule_id DESC
    LIMIT 1
  )
  SELECT b.quick_rule_id,b.product_code,b.model_code,b.material_code,
         b.reference_width_mm,b.reference_height_mm,b.reference_depth_mm,
         b.quick_material_cost,b.quick_auxiliary_cost,b.quick_labor_cost,
         b.quick_attachment_fee,b.quick_spray_cost,b.quick_management_fee,
         ROUND(
           COALESCE(b.quick_base_price,b.quick_total_cost)
           * CASE
               WHEN 4 * (b.reference_width_mm + b.reference_height_mm + b.reference_depth_mm) > 0
               THEN 4 * (p_width_mm + p_height_mm + p_depth_mm)
                    / (4 * (b.reference_width_mm + b.reference_height_mm + b.reference_depth_mm))
               ELSE 1
             END,
           6
         ),
         CASE
           WHEN b.model_rank = 0 AND b.distance = 0 THEN 'exact_model_dimension'
           WHEN b.range_rank = 0 THEN 'dimension_range'
           ELSE 'nearest_dimension'
         END::VARCHAR,
         b.distance
  FROM best b;
$function$;

