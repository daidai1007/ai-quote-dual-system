ALTER TABLE calc.dual_quote_result
  ADD COLUMN IF NOT EXISTS quick_base_price NUMERIC(14,6);

COMMENT ON COLUMN calc.dual_quote_result.quick_attachment_fee IS
  'Selected attachment fee added to the quick experience base price.';

CREATE OR REPLACE FUNCTION calc.calculate_dual_quote(
  p_quote_id VARCHAR,
  p_product_code VARCHAR,
  p_model_code VARCHAR,
  p_material_code VARCHAR,
  p_width_mm NUMERIC,
  p_height_mm NUMERIC,
  p_depth_mm NUMERIC,
  p_base_material_weight_kg NUMERIC DEFAULT NULL,
  p_product_area_m2 NUMERIC DEFAULT NULL,
  p_coating_type VARCHAR DEFAULT U&'\5E73\5149',
  p_variant_code VARCHAR DEFAULT NULL,
  p_quote_date DATE DEFAULT CURRENT_DATE
)
RETURNS TABLE (
  quote_id VARCHAR,
  product_code VARCHAR,
  model_code VARCHAR,
  material_code VARCHAR,
  formula_material_cost NUMERIC,
  formula_auxiliary_cost NUMERIC,
  formula_labor_cost NUMERIC,
  formula_attachment_fee NUMERIC,
  formula_product_area_m2 NUMERIC,
  formula_spray_cost NUMERIC,
  formula_management_fee NUMERIC,
  formula_total_cost NUMERIC,
  quick_rule_id BIGINT,
  quick_match_method VARCHAR,
  quick_match_distance NUMERIC,
  quick_material_cost NUMERIC,
  quick_auxiliary_cost NUMERIC,
  quick_labor_cost NUMERIC,
  quick_attachment_fee NUMERIC,
  quick_spray_cost NUMERIC,
  quick_management_fee NUMERIC,
  quick_total_cost NUMERIC,
  difference_cost NUMERIC,
  risk_flags JSONB
)
LANGUAGE plpgsql
VOLATILE
AS $function$
DECLARE
  v_formula RECORD;
  v_quick RECORD;
  v_risks JSONB := '[]'::jsonb;
  v_product_code VARCHAR;
  v_quick_attachment NUMERIC := 0;
  v_quick_base NUMERIC;
  v_quick_total NUMERIC;
  v_difference NUMERIC;
BEGIN
  IF p_quote_id IS NULL OR btrim(p_quote_id) = '' THEN
    RAISE EXCEPTION 'quote_id is required';
  END IF;
  IF p_material_code NOT IN ('SECC','SUS304','SUS316') THEN
    RAISE EXCEPTION 'unsupported material_code: %', p_material_code;
  END IF;
  IF p_width_mm IS NULL OR p_height_mm IS NULL OR p_depth_mm IS NULL
     OR p_width_mm <= 0 OR p_height_mm <= 0 OR p_depth_mm <= 0 THEN
    RAISE EXCEPTION 'width, height and depth must be positive';
  END IF;

  v_product_code := CASE p_product_code
    WHEN 'JC' THEN 'JC_EXP'
    WHEN 'JQ' THEN 'JQ_EXP'
    WHEN U&'\8D85\5BBDJP' THEN 'JP_WIDE_EXP'
    WHEN U&'\8D85\5BBDJS' THEN 'JS_WIDE_EXP'
    WHEN U&'\64CD\4F5C\53F0' THEN 'OP_TABLE_EXP'
    ELSE p_product_code END;

  /* Formula quotation remains the existing DB-owned calculation. */
  SELECT * INTO v_formula
  FROM calc.calculate_quote_total(
    p_quote_id, v_product_code, COALESCE(p_model_code,''), p_material_code,
    p_width_mm, p_height_mm, p_depth_mm, p_base_material_weight_kg,
    p_product_area_m2, p_coating_type, p_variant_code, p_quote_date);

  IF v_formula.material_cost IS NULL THEN
    v_risks := v_risks || jsonb_build_array(jsonb_build_object(
      'code','formula_material_cost_missing','severity','blocker'));
  END IF;

  /* Quick quotation reads experience values only. */
  SELECT * INTO v_quick
  FROM calc.match_quick_quote(
    v_product_code, p_model_code, p_material_code,
    p_width_mm, p_height_mm, p_depth_mm, p_quote_date);

  IF NOT FOUND THEN
    v_risks := v_risks || jsonb_build_array(jsonb_build_object(
      'code','quick_quote_missing','severity','blocker',
      'message',U&'\5F85\8865\5145\7ECF\9A8C\503C'));
    v_quick_total := NULL;
  ELSE
    /* match_quick_quote returns the direct quick base in quick_total_cost.
       It intentionally does not expose formula-derived components. */
    v_quick_base := v_quick.quick_total_cost;
    v_quick_attachment := COALESCE(calc.get_attachment_fee(p_quote_id, v_product_code), 0);
    v_quick_total := v_quick_base + v_quick_attachment;
  END IF;

  IF v_formula.total_cost IS NOT NULL AND v_quick_total IS NOT NULL THEN
    v_difference := ROUND(v_quick_total - v_formula.total_cost, 2);
  END IF;

  /* A quote_id is the logical version key. Replace the previous snapshot
     before writing the new one; this also makes repeated smoke tests safe. */
  DELETE FROM calc.dual_quote_result
   WHERE calc.dual_quote_result.quote_id = $1;

  INSERT INTO calc.dual_quote_result(
    quote_id,product_code,model_code,material_code,
    input_width_mm,input_height_mm,input_depth_mm,quote_date,
    formula_material_cost,formula_auxiliary_cost,formula_labor_cost,
    formula_attachment_fee,formula_product_area_m2,formula_spray_cost,
    formula_management_fee,formula_total_cost,
    quick_rule_id,quick_match_method,quick_match_distance,
    quick_material_cost,quick_auxiliary_cost,quick_labor_cost,
    quick_attachment_fee,quick_spray_cost,quick_management_fee,quick_base_price,
    quick_total_cost,difference_cost,risk_flags,updated_at)
  VALUES(
    p_quote_id,v_product_code,p_model_code,p_material_code,
    p_width_mm,p_height_mm,p_depth_mm,p_quote_date,
    v_formula.material_cost,v_formula.auxiliary_cost,v_formula.labor_cost,
    v_formula.attachment_fee,v_formula.product_area_m2,v_formula.spray_cost,
    v_formula.management_fee,v_formula.total_cost,
    v_quick.quick_rule_id,v_quick.match_method,v_quick.dimension_distance,
    v_quick.quick_material_cost,v_quick.quick_auxiliary_cost,v_quick.quick_labor_cost,
    v_quick_attachment,v_quick.quick_spray_cost,v_quick.quick_management_fee,v_quick_base,
    v_quick_total,v_difference,v_risks,now());

  RETURN QUERY SELECT
    p_quote_id,v_product_code,p_model_code,p_material_code,
    v_formula.material_cost,v_formula.auxiliary_cost,v_formula.labor_cost,
    v_formula.attachment_fee,v_formula.product_area_m2,v_formula.spray_cost,
    v_formula.management_fee,v_formula.total_cost,
    v_quick.quick_rule_id,v_quick.match_method,v_quick.dimension_distance,
    v_quick.quick_material_cost,v_quick.quick_auxiliary_cost,v_quick.quick_labor_cost,
    v_quick_attachment,v_quick.quick_spray_cost,v_quick.quick_management_fee,
    v_quick_total,v_difference,v_risks;
END;
$function$;

COMMENT ON FUNCTION calc.calculate_dual_quote IS
  'Returns formula quotation and independent quick experience quotation in one call. Quick total is experience base price plus selected attachment fee; missing quick values remain NULL and are flagged.';

COMMIT;

