// Fully disposable loopback PostgreSQL. Never reads application DB settings.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import test from 'node:test';
import {startLocalPostgres} from './helpers/local_postgres.mjs';
import {sqlValue} from '../api/attachment_service.mjs';
import {createQuickMatchOverrideService} from '../api/quick_match_override.mjs';

const json=value=>`${sqlValue(JSON.stringify(value))}::jsonb`;
test('real PostgreSQL manual matching preserves source precision, scales by actual dimensions and atomically appends ordinary/ganged snapshots',
  {timeout:120000},async()=>{
  const cluster=await startLocalPostgres();
  const query=text=>cluster.query(text);
  try {
    query(`CREATE SCHEMA calc;
      CREATE TABLE calc.quick_quote_experience(
        quick_rule_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        product_code varchar(40) NOT NULL,model_code varchar(100),material_code varchar(30) NOT NULL,
        reference_width_mm numeric NOT NULL,reference_height_mm numeric NOT NULL,reference_depth_mm numeric NOT NULL,
        min_width_mm numeric,max_width_mm numeric,min_height_mm numeric,max_height_mm numeric,min_depth_mm numeric,max_depth_mm numeric,
        quick_material_cost numeric,quick_auxiliary_cost numeric,quick_labor_cost numeric,quick_attachment_fee numeric,
        quick_spray_cost numeric,quick_management_fee numeric,quick_base_price numeric,quick_total_cost numeric NOT NULL,
        effective_from date NOT NULL,effective_to date,is_active boolean NOT NULL DEFAULT true,
        source_file text,source_sheet text,source_row_no integer);
      INSERT INTO calc.quick_quote_experience(product_code,material_code,reference_width_mm,reference_height_mm,
        reference_depth_mm,quick_base_price,quick_total_cost,effective_from) VALUES
        ('JE_SINGLE','SECC',1200,565,365,1000,1000,'2026-01-01'),
        ('JA_SINGLE','SECC',590,600,230,500,500,'2026-01-01'),
        ('JA_SINGLE','SECC',600,600,250,627.6723456789,627.6723456789,'2026-01-01'),
        ('JA_SINGLE','SECC',800,2000,600,1400,1400,'2026-01-01');
      CREATE TABLE calc.attachment_quote_line(
        quote_line_id uuid PRIMARY KEY,quote_id varchar(80) NOT NULL,product_code varchar(40) NOT NULL,
        environment_snapshot jsonb NOT NULL,
        CHECK(environment_snapshot->>'product_code'=product_code
          AND (environment_snapshot->>'width_mm')::numeric>0
          AND (environment_snapshot->>'height_mm')::numeric>0
          AND (environment_snapshot->>'depth_mm')::numeric>0));`);
    query(fs.readFileSync(path.resolve('database/migrations/enforce_quick_quote_dimension_only.sql'),'utf8'));
    const formula={material_cost:100,auxiliary_cost:10,labor_cost:20,spray_cost:30,attachment_fee:20,total_cost:190};
    const environment={product_code:'JA',material_code:'SECC',width_mm:590,depth_mm:230,height_mm:600,
      quote_date:'2026-10-19',coating_type:'橘纹',density_g_cm3:7.85,material_unit_price:4.2,spray_unit_price:26,
      ganged_cabinet_count:1,ganged_cabinets:[],quote_result:{quote_id:'local-regression',formula_cost:formula,
        quick_quote:{base_price:500,attachment_fee:20,total_cost:520}}};
    const id='11111111-1111-4111-8111-111111111111';
    const size={width_mm:600,depth_mm:250,height_mm:600};
    query(`INSERT INTO calc.attachment_quote_line VALUES('${id}','local-regression','JA',${json(environment)});`);
    const service=createQuickMatchOverrideService({runPsql:async text=>query(text)});
    const result=await service({quote_line_id:id,matched_sizes:[size]});
    const expected=Number(query('SELECT ROUND(627.6723456789::numeric*(590+230+600)/(600+250+600),6);'));
    assert.equal(result.quick_quote.base_price,expected);
    assert.equal(result.quick_quote.matched_experience.quick_base_price,627.6723456789);
    const old=JSON.parse(query(`SELECT environment_snapshot FROM calc.attachment_quote_line WHERE quote_line_id='${id}';`));
    assert.deepEqual(old,environment);
    const updated=JSON.parse(query(`SELECT environment_snapshot FROM calc.attachment_quote_line WHERE quote_line_id='${result.quote_line_id}';`));
    assert.equal(updated.width_mm,590);
    assert.deepEqual(updated.quote_result.formula_cost,formula);
    assert.equal(updated.quick_match_source_line_id,id);
    const before=query('SELECT count(*) FROM calc.attachment_quote_line;');
    await assert.rejects(service({quote_line_id:id,matched_sizes:[{...size,width_mm:601}]}),/没有完全对应/);
    assert.equal(query('SELECT count(*) FROM calc.attachment_quote_line;'),before);
    const badSave=createQuickMatchOverrideService({runPsql:async sql=>query(sql.startsWith('BEGIN;')
      ? sql.replace('COMMIT;','SELECT intentional_missing_function(); COMMIT;') : sql)});
    await assert.rejects(badSave({quote_line_id:id,matched_sizes:[size]}));
    assert.equal(query('SELECT count(*) FROM calc.attachment_quote_line;'),before);
    const other='22222222-2222-4222-8222-222222222222';
    const child2={width_mm:800,depth_mm:600,height_mm:2000};
    const ganged={...environment,ganged_cabinet_count:2,
      ganged_cabinets:[{width_mm:590,depth_mm:230,height_mm:600},child2]};
    query(`INSERT INTO calc.attachment_quote_line VALUES('${other}','local-ganged','JA',${json(ganged)});`);
    const both=await service({quote_line_id:other,matched_sizes:[size,child2]});
    assert.equal(both.quick_quote.base_price,Math.round((expected+1400)*1e6)/1e6);
    assert.equal(both.quick_quote.matched_experience.items.length,2);
    assert.equal(query('SELECT quick_base_price FROM calc.quick_quote_experience WHERE reference_width_mm=600;'),'627.6723456789');
  } finally { await cluster.close(); }
});
